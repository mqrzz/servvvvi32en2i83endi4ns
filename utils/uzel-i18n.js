// язык посетителя по Accept-Language, если у страницы язык не задан
function fromHeader(h) {
  const parts = String(h || '').split(',').map((s) => s.trim().split(';')[0].toLowerCase().slice(0, 2)).filter(Boolean);
  return parts.find((p) => PUB[p]) || DEFAULT_LANG;
}
